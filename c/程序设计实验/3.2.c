#include <stdio.h>
#include <math.h>
int main()
{
    double p1, p2, p3, p4, p5;
    p1 = 1000 * (1 + 5 * 0.03);
    p2 = 1000 * (1 + 2 * 0.021) * (1 + 3 * 0.0275);
    p3 = 1000 * (1 + 3 * 0.0275) * (1 + 2 * 0.021);
    p4 = 1000 * pow(1 + 0.015, 5);
    p5 = 1000 * pow(1 + 0.0035 / 4, 5 * 4);
    printf("一次存5年：%.2f元\n", p1);
    printf("先存2年再存3年：%.2f元\n", p2);
    printf("先存3年再存2年：%.2f元\n", p3);
    printf("连续存5次1年期：%.2f元\n", p4);
    printf("存5年活期：%.2f元\n", p5);

    return 0;
}